function path(grid) {
  let d = "";
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let w = 1;
        while (row[x + w] === "#") w++;
        d += `M${x} ${y}h${w}v1h-${w}z`;
        x += w;
      } else x++;
    }
  });
  return d;
}

function icon(name, cls = "px") {
  const g = grids[name];
  if (!g) throw new Error("ikon yok: " + name);
  return `<svg class="${cls}" viewBox="0 0 12 12" aria-hidden="true" focusable="false"><path d="${path(g)}"/></svg>`;
}

module.exports = { icon, path, grids };
